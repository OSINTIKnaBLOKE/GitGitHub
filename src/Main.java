/*
 * Основные команды Git:
 *
 * git init - Инициализирует новый Git-репозиторий в текущей директории
 * git clone <url> - Клонирует репозиторий из URL в новую директорию
 * git add <файл> - Добавляет файл в индекс для следующего коммита
 * git commit -m "сообщение" - Фиксирует подготовленные изменения в репозитории
 * git push - Отправляет изменения из локального репозитория в удаленный
 * git pull - Обновляет текущую ветку с последней версией из удаленного репозитория
 * git branch - Показывает, создает или удаляет ветки
 * git merge <ветка> - Сливает изменения указанной ветки в текущую ветку
 * git log - Показывает историю коммитов ветки
 * git reflog - Показывает журнал всех локальных действий (переключения, коммиты, откаты)
 * git reset --hard <хэш> - Жестко откатывает проект к указанному коммиту (например, 245424a)
 * git push -u origin feature/add-usage-examples - Отправляет новую ветку на GitHub и связывает ее с удаленной
 *
 *
 * Меню Git сверху на панели Intellij IDEA
 *
 * Commit - открывает окно для коммита
 * Push - открывает окно для отправки ваших коммитов на GitHub
 * Update Project - очень важная функция.
 * Она скачивает свежие изменения от других участников команды (выполняет git pull).
 * Нажимать ее каждое утро перед началом работы
 * Branches - открывает окно для управления ветками. С этим разберемся в следующих лекциях
 * Show Git Log - показывает всю историю коммитов вашего проекта. Ваша личная машина времени
 *
 * можно добавлять файлы в .gitignore пкм по файлу -> Git -> add gitignore -> gitignore
 * что бы не отправлялись на GitHub
 *
 * //TODO ВАЖНО! Локальные правила игнорирования действует только для вашей локаальной копии репозитория
 **/

/*
* * - заменяет любое количество символов. Например, *.log игнорирует все файл с разрешением .log
* / - в конце шаблона означает директорию. Например, .logs/ игнорирует все содержимое папки logs
* ! - в начале строки инвертирует правило. Например, если у вас есть правило *.log, но вы не хотите отслеживать important.log,
*  добавьте строку !important.log
*
* ** - соответствует любому кол-во вложенных папок. Например, **=/temp (без =) игнорирует папки temp на любом уровне вложенности
* */