public class Main {
    /**
     * @returns основные команды гит
     * @returns git init - Инициализирует новый Git-репозиторий в текущую директорию
     * @returns git clone - Клонирует репозиторий из URL в новою директорию
     * @returns git add - добавляет файл в индекс для следующего коммита
     * @returns git commit -m "что то в кавычках" - Фиксирует подготовленные изменения в репозитории
     * @returns git push - Отправляет изменения из локального репозитория в удаленный
     * @returns git pull - Обновляет текущую ветку с последней версией из удаленного репозитория
     * @returns git branch - Показывает, создает или удаляет ветку
     * @returns git merge - Сливает изменения указанной ветки в текущую ветку
     * @returns git log - показывает все снимки проекта(коммиты)
     * @returns git reflog - показывает журнал перемещений указателя HEAD
     * @returns git reset --hard 245424a - откатить коммит (в конце это хеш коммита)
     * @returns git push -u origin feature/add-usage-examples - отправить ветку в гитхаб на слияние
     *
     */

    /*
     * Основные команды Git:
     *
     * git init - Инициализирует новый Git-репозиторий в текущей директории
     * git clone <url> - Клонирует репозиторий из URL в новую директорию
     * git add <файл> - Добавляет файл в индекс для следующего коммита
     * git commit -m "сообщение" - Фиксирует подготовленные изменения в репозитории
     * git push - Отправляет изменения из локального репозитория в удаленный
     * git pull - Обновляет текущую ветку с последней версией из удаленного репозитория
     * git branch - Показывает, создает или удаляет ветки
     * git merge <ветка> - Сливает изменения указанной ветки в текущую ветку
     * git log - Показывает историю коммитов ветки
     * git reflog - Показывает журнал всех локальных действий (переключения, коммиты, откаты)
     * git reset --hard <хэш> - Жестко откатывает проект к указанному коммиту (например, 245424a)
     * git push -u origin feature/add-usage-examples - Отправляет новую ветку на GitHub и связывает ее с удаленной
     */


    static void main() {
        int i = 0;
        for (int j = 0; j < 10; j++) {
            i += j;
        }

        System.out.println(i);

        System.out.println(i - 1);
    }
}